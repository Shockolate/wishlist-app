import { sql } from 'drizzle-orm';
import {
  boolean,
  check,
  index,
  integer,
  pgTable,
  primaryKey,
  text,
  timestamp,
  unique,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';

const tz = { withTimezone: true } as const;

// A function, not a shared object: each table needs its own column builders.
const timestamps = () => ({
  createdAt: timestamp('created_at', tz).notNull().defaultNow(),
  updatedAt: timestamp('updated_at', tz).notNull().defaultNow(),
});

/** Fixed-window counters for rate limiting (spec §4, §6.6): one row per key per window. */
export const rateLimits = pgTable(
  'rate_limits',
  {
    key: text('key').notNull(),
    windowStart: timestamp('window_start', tz).notNull(),
    count: integer('count').notNull(),
  },
  (t) => [primaryKey({ columns: [t.key, t.windowStart] })],
);

/**
 * Accounts (spec §4). IDs are UUIDv7, generated by the application. Emails are stored lowercased,
 * and the unique index on lower(email) holds even if a write ever forgets to.
 */
export const users = pgTable(
  'users',
  {
    id: uuid('id').primaryKey(),
    email: text('email').notNull(),
    /** An argon2id PHC string. */
    passwordHash: text('password_hash').notNull(),
    displayName: text('display_name').notNull(),
    emailVerifiedAt: timestamp('email_verified_at', tz),
    ...timestamps(),
  },
  (t) => [uniqueIndex('users_email_lower_key').on(sql`lower(${t.email})`)],
);

/** Database sessions (spec §6.1). The id is SHA-256 of the cookie token, so a leak yields nothing usable. */
export const sessions = pgTable(
  'sessions',
  {
    id: text('id').primaryKey(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    createdAt: timestamp('created_at', tz).notNull().defaultNow(),
    expiresAt: timestamp('expires_at', tz).notNull(),
    lastSeenAt: timestamp('last_seen_at', tz).notNull(),
  },
  (t) => [index('sessions_user_id_idx').on(t.userId)],
);

export const EMAIL_TOKEN_PURPOSES = ['verify_email', 'reset_password'] as const;
export type EmailTokenPurpose = (typeof EMAIL_TOKEN_PURPOSES)[number];

/** Verify and reset links (spec §4, §6.5). Only the SHA-256 of each token is stored. */
export const emailTokens = pgTable(
  'email_tokens',
  {
    id: uuid('id').primaryKey(),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    purpose: text('purpose', { enum: EMAIL_TOKEN_PURPOSES }).notNull(),
    tokenHash: text('token_hash').notNull().unique(),
    expiresAt: timestamp('expires_at', tz).notNull(),
    consumedAt: timestamp('consumed_at', tz),
    createdAt: timestamp('created_at', tz).notNull().defaultNow(),
  },
  (t) => [
    index('email_tokens_user_id_idx').on(t.userId),
    check('email_tokens_purpose_check', sql`${t.purpose} in ('verify_email', 'reset_password')`),
  ],
);

/**
 * One list per user (spec §2, D4), enforced by the unique owner_id rather than by hanging items off
 * users. Signup creates it. The share token is plaintext by design: the owner must always be able
 * to copy the link (spec §4).
 */
export const wishlists = pgTable('wishlists', {
  id: uuid('id').primaryKey(),
  ownerId: uuid('owner_id')
    .notNull()
    .unique()
    .references(() => users.id, { onDelete: 'cascade' }),
  title: text('title').notNull(),
  shareToken: text('share_token').notNull().unique(),
  showClaimsToOwner: boolean('show_claims_to_owner').notNull().default(false),
  suggestTags: boolean('suggest_tags').notNull().default(true),
  ...timestamps(),
});

/**
 * Items (spec §2, §4). An idea is an item without a url. The server sets `position`, under a lock
 * on the owner's wishlist row (spec §5).
 */
export const items = pgTable(
  'items',
  {
    id: uuid('id').primaryKey(),
    wishlistId: uuid('wishlist_id')
      .notNull()
      .references(() => wishlists.id, { onDelete: 'cascade' }),
    title: text('title').notNull(),
    url: text('url'),
    imageUrl: text('image_url'),
    priceText: text('price_text'),
    note: text('note'),
    quantity: integer('quantity').notNull(),
    position: integer('position').notNull(),
    ...timestamps(),
  },
  (t) => [
    index('items_wishlist_id_position_idx').on(t.wishlistId, t.position),
    check('items_quantity_check', sql`${t.quantity} between 1 and 99`),
  ],
);

/**
 * Claims (spec §2, §4): who is getting how many of an item. Remaining is computed, never stored.
 * A claim reaches its list through its item, so deleting the item, the list or the account takes
 * the claim with it. The manage token is shown once; only its SHA-256 is kept.
 */
export const claims = pgTable(
  'claims',
  {
    id: uuid('id').primaryKey(),
    itemId: uuid('item_id')
      .notNull()
      .references(() => items.id, { onDelete: 'cascade' }),
    claimerName: text('claimer_name').notNull(),
    quantity: integer('quantity').notNull(),
    manageTokenHash: text('manage_token_hash').notNull().unique(),
    ...timestamps(),
  },
  (t) => [
    index('claims_item_id_idx').on(t.itemId),
    check('claims_quantity_check', sql`${t.quantity} >= 1`),
  ],
);

/**
 * Your gifts (design §4, D76, D80): a signed-in gifter's private link to a claim, plus the
 * bookkeeping that belongs to the gifter and not to the claim (the Bought tick). `claim_id` sets
 * null, not cascades, when the claim goes: the owner deleting the item, the list or the account, or
 * a manage-link cancel, must leave the gifter a note saying what became of the claim. `item_title`
 * and `owner_display_name` are snapshots for that note. `gone_at` is when the claim went and
 * `cancelled_at` says it was cancelled through its link; a note lives 30 days from `gone_at`.
 * Deleting the gifter's account deletes their links and never the claims (D79). One link per claim,
 * so a claim is on at most one account's gifts; a null `claim_id` is not unique, so notes pile up.
 */
export const claimLinks = pgTable(
  'claim_links',
  {
    id: uuid('id').primaryKey(),
    claimId: uuid('claim_id').references(() => claims.id, { onDelete: 'set null' }),
    userId: uuid('user_id')
      .notNull()
      .references(() => users.id, { onDelete: 'cascade' }),
    boughtAt: timestamp('bought_at', tz),
    cancelledAt: timestamp('cancelled_at', tz),
    goneAt: timestamp('gone_at', tz),
    itemTitle: text('item_title').notNull(),
    ownerDisplayName: text('owner_display_name').notNull(),
    ...timestamps(),
  },
  (t) => [
    unique('claim_links_claim_id_unique').on(t.claimId),
    index('claim_links_user_id_idx').on(t.userId),
  ],
);

/**
 * Tags (design §5): labels the owner makes to sort their list. A tag belongs to one wishlist, and
 * deleting the list or the account takes it away. `name` keeps the spelling the owner first used;
 * `nameKey` is its case-folded form (`keyOfCleanName` for a name `TagNameSchema` has cleaned, `tagKey`
 * in the contracts for raw input), so "Kitchen" and "kitchen" are one tag. The key is computed by
 * the API, not by the database.
 */
export const tags = pgTable(
  'tags',
  {
    id: uuid('id').primaryKey(),
    wishlistId: uuid('wishlist_id')
      .notNull()
      .references(() => wishlists.id, { onDelete: 'cascade' }),
    name: text('name').notNull(),
    nameKey: text('name_key').notNull(),
    ...timestamps(),
  },
  (t) => [unique('tags_wishlist_id_name_key_unique').on(t.wishlistId, t.nameKey)],
);

/**
 * Which tags an item carries (design §5). Deleting either side removes the link and never the
 * other side. The primary key serves lookups by item; the index serves lookups and deletes by tag.
 * The limits on tags per item and per list are enforced by the API, under the list lock.
 */
export const itemTags = pgTable(
  'item_tags',
  {
    itemId: uuid('item_id')
      .notNull()
      .references(() => items.id, { onDelete: 'cascade' }),
    tagId: uuid('tag_id')
      .notNull()
      .references(() => tags.id, { onDelete: 'cascade' }),
  },
  (t) => [primaryKey({ columns: [t.itemId, t.tagId] }), index('item_tags_tag_id_idx').on(t.tagId)],
);
